using Markdig.Syntax;
using Markdig.Syntax.Inlines;
using RazorFolio.Core.Output;

namespace RazorFolio.Core.Diagnostics;

public sealed class ContentLinkChecker
{
    private readonly string outputDirectory;
    private readonly Uri siteUri;
    private readonly HashSet<string> generatedPaths;

    public ContentLinkChecker(string outputDirectory, IEnumerable<string> outputPaths, string? siteUrl)
    {
        this.outputDirectory = outputDirectory;
        siteUri = new Uri(siteUrl ?? "https://razorfolio.invalid/");
        generatedPaths = outputPaths.Select(path =>
            Path.GetRelativePath(outputDirectory, path).Replace(Path.DirectorySeparatorChar, '/'))
            .ToHashSet(StringComparer.Ordinal);
    }

    public IEnumerable<ContentLinkDiagnostic> Check(
        MarkdownDocument document, string sourcePath, string originalPath, string outputPath,
        ContentLinkResolver resolver)
    {
        var pageUri = new Uri(PageUrl.GetAbsolute(outputPath, outputDirectory, siteUri.AbsoluteUri)!);
        foreach (var link in document.Descendants<LinkInline>())
        {
            // Dynamic links (for example generated footnote navigation) are not authored URL targets.
            if (link.GetDynamicUrl is not null || link.Url is not { Length: > 0 } url) continue;
            if (url[0] is '#' or '?' || url.StartsWith("//", StringComparison.Ordinal)) continue;
            if (url[0] != '/' && Uri.TryCreate(url, UriKind.Absolute, out _)) continue;

            var issue = FindIssue(url, originalPath, outputPath, pageUri, resolver);
            if (issue is { } value)
            {
                yield return new ContentLinkDiagnostic(
                    sourcePath, link.Line + 1, link.Column + 1, value.Code, url, value.Message);
            }
        }
    }

    private (string Code, string Message)? FindIssue(
        string url, string originalPath, string outputPath, Uri pageUri, ContentLinkResolver resolver)
    {
        if (url.Contains('\\'))
            return ("RF1004", "Use forward slashes in a local URL.");

        var rewritten = resolver.Resolve(url, originalPath, outputPath);
        if (!Uri.TryCreate(pageUri, rewritten, out var target))
            return ("RF1004", "Invalid local URL.");

        var sitePath = Uri.UnescapeDataString(siteUri.AbsolutePath);
        var targetPath = Uri.UnescapeDataString(target.AbsolutePath);
        string relativePath;
        if (targetPath == sitePath.TrimEnd('/'))
            relativePath = "";
        else if (targetPath.StartsWith(sitePath, StringComparison.Ordinal))
            relativePath = targetPath[sitePath.Length..];
        else
            return ("RF1003", $"Local URL is outside the configured site path '{sitePath}'.");

        // Never consult existing output files: stale files must not hide links to removed content or drafts.
        if (generatedPaths.Contains(relativePath)) return null;
        var indexPath = relativePath.Length == 0 ? "index.html" : relativePath.TrimEnd('/') + "/index.html";
        if (generatedPaths.Contains(indexPath)) return null;

        var caseMatch = generatedPaths.FirstOrDefault(path =>
            string.Equals(path, relativePath, StringComparison.OrdinalIgnoreCase)
            || string.Equals(path, indexPath, StringComparison.OrdinalIgnoreCase));
        if (caseMatch is not null)
            return ("RF1002", $"URL casing differs from generated target '{caseMatch}'.");

        return ("RF1001", $"Local target is not generated by this build: '{relativePath}'.");
    }
}
